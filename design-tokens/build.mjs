// Generates the web CSS and the app theme from tokens.json, so both stay identical.
// Usage: node design-tokens/build.mjs [--mobile ../docnow-mobile]
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const t = JSON.parse(readFileSync(join(here, 'tokens.json'), 'utf8'));
const strip = (o) => Object.fromEntries(Object.entries(o).filter(([k]) => !k.startsWith('$')));
const colors = strip(t.color);
const legacy = strip(t.legacy);
const header = 'GENERATED by design-tokens/build.mjs from tokens.json. Do not edit; edit tokens.json and rebuild.';

export function webCss() {
    const lines = [`/* ${header} */`, '@theme {'];
    for (const [k, v] of Object.entries(colors)) lines.push(`  --color-${k}: ${v};`);
    for (const [k, v] of Object.entries(legacy)) lines.push(`  --color-${k}: var(--color-${v});`);
    for (const [k, v] of Object.entries(t.radius)) lines.push(`  --radius-${k}: ${v}px;`);
    lines.push(`  --shadow-raised: ${t.shadow.raised.css};`);
    lines.push('}');
    // Plain variables too, for the few places that read them directly.
    lines.push('', ':root {');
    for (const [k, v] of Object.entries(colors)) lines.push(`  --${k}: ${v};`);
    for (const [k, v] of Object.entries(legacy)) lines.push(`  --${k}: var(--${v});`);
    lines.push(`  --radius: ${t.radius.xl}px;`, '}', '');
    return lines.join('\n');
}

const camel = (k) => k.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const tsObject = (o, indent = '  ') =>
    '{\n' + Object.entries(o).map(([k, v]) => {
        const key = /^[a-zA-Z_]\w*$/.test(k) ? k : `'${k}'`;
        const val = typeof v === 'object' ? tsObject(v, indent + '  ') : typeof v === 'string' ? `'${v}'` : v;
        return `${indent}  ${key}: ${val},`;
    }).join('\n') + `\n${indent}}`;

export function nativeTs() {
    const camelKeys = (o) => Object.fromEntries(Object.entries(o).map(([k, v]) => [camel(k), v]));
    const sizes = Object.fromEntries(Object.entries(t.font.size).map(([k, [size, line]]) => [camel(k), { fontSize: size, lineHeight: line }]));
    const weights = Object.fromEntries(Object.entries(t.font.weight).map(([k, v]) => [k, String(v)]));
    const s = t.shadow.raised.native;
    const shadow = { shadowColor: s.color, shadowOpacity: s.opacity, shadowRadius: s.radius, shadowOffset: { width: 0, height: s.offsetY }, elevation: s.elevation };
    return [
        `// ${header}`,
        `export const Tokens = {`,
        `  color: ${tsObject(camelKeys(colors), '  ')},`,
        `  fontSize: ${tsObject(sizes, '  ')},`,
        `  fontWeight: ${tsObject(weights, '  ')},`,
        `  space: ${tsObject(t.space, '  ')},`,
        `  radius: ${tsObject(t.radius, '  ')},`,
        `  shadowRaised: ${tsObject(shadow, '  ')},`,
        `} as const;`,
        '',
    ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    writeFileSync(resolve(here, '../client/src/app/tokens.css'), webCss());
    console.log('wrote client/src/app/tokens.css');
    const i = process.argv.indexOf('--mobile');
    if (i > 0) {
        const root = resolve(process.cwd(), process.argv[i + 1]);
        const out = join(root, 'src/constants/tokens.ts');
        if (!existsSync(join(root, 'package.json'))) throw new Error(`No app at ${root}`);
        writeFileSync(out, nativeTs());
        console.log(`wrote ${out}`);
    }
}
